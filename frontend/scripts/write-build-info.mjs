// Writes src/generated/build-info.ts with the current date/time so the footer
// version code always reflects the actual build. Runs via the `prebuild` hook.
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const now = new Date();
const pad = (n) => String(n).padStart(2, "0");

const version = `${now.getFullYear()}.${pad(now.getMonth() + 1)}.${pad(now.getDate())}-${pad(now.getHours())}${pad(now.getMinutes())}`;
const builtAt = now.toLocaleString("en-US", {
  day: "2-digit",
  month: "short",
  year: "numeric",
  hour: "numeric",
  minute: "2-digit",
});

const out = `// Auto-generated by scripts/write-build-info.mjs at build time. Do not edit.
export const BUILD_INFO = {
  version: ${JSON.stringify(version)},
  builtAt: ${JSON.stringify(builtAt)},
} as const;
`;

mkdirSync(join(root, "src", "generated"), { recursive: true });
writeFileSync(join(root, "src", "generated", "build-info.ts"), out);
console.log(`build-info: ${version} | ${builtAt}`);
