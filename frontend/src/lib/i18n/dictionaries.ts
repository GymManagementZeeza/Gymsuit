const dictionaries: Record<Locale, DeepPartial<Dictionary>> = { en, ml };

function deepMerge(base: Dictionary, override: DeepPartial<Dictionary>): Dictionary {
  if (typeof override === "function" || typeof base !== "object" || base === null) {
    return (override === undefined ? base : override) as Dictionary;
  }
  const result: Record<string, unknown> = { ...(base as Record<string, unknown>) };
  for (const key of Object.keys(override as Record<string, unknown>)) {
    const baseValue = (base as Record<string, unknown>)[key];
    const overrideValue = (override as Record<string, unknown>)[key];
    result[key] =
      overrideValue !== undefined &&
      typeof baseValue === "object" &&
      baseValue !== null &&
      typeof overrideValue === "object" &&
      typeof baseValue !== "function"
        ? deepMerge(baseValue as Dictionary, overrideValue as DeepPartial<Dictionary>)
        : (overrideValue ?? baseValue);
  }
  return result as Dictionary;
}

/** Resolve the full typed dictionary for a locale, falling back to English for missing keys. */
export function resolveDictionary(locale: Locale): Dictionary {
  if (locale === "en") return en;
  return deepMerge(en, dictionaries[locale] ?? {});
}

/** BCP 47 tag for Intl formatting. */
export function intlLocale(locale: Locale): string {
  return locale === "ml" ? "ml-IN" : "en-IN";
}
